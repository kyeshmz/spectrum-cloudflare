// Development-only generator. Runtime modules have no Node dependencies.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const snapshot = new URL('spec/spectrum-openapi.json', root);
const check = process.argv[2] === '--check';
if (process.argv[2] && !check) {
  mkdirSync(new URL('spec/', root), { recursive: true });
  writeFileSync(snapshot, JSON.stringify(JSON.parse(readFileSync(process.argv[2], 'utf8')), null, 2) + '\n');
}
const raw = readFileSync(snapshot, 'utf8');
const spec = JSON.parse(raw);
const hash = createHash('sha256').update(raw).digest('hex');
function type(schema = {}) {
  if ('$ref' in schema) throw new Error(`Unsupported reference: ${schema.$ref}`);
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((x) => JSON.stringify(x)).join(' | ');
  if (schema.oneOf || schema.anyOf) return '(' + (schema.oneOf ?? schema.anyOf).map(type).join(' | ') + ')';
  if (schema.type === 'array') return `Array<${type(schema.items)}>`;
  if (schema.type === 'object') {
    const fields = Object.entries(schema.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${type(value)};`);
    if (schema.additionalProperties !== false && schema.additionalProperties !== undefined) fields.push(`[key: string]: ${Object.keys(schema.properties ?? {}).length ? 'unknown' : type(schema.additionalProperties === true ? {} : schema.additionalProperties)};`);
    return fields.length ? `{ ${fields.join(' ')} }` : 'Record<string, never>';
  }
  return ({ string: 'string', integer: 'number', number: 'number', boolean: 'boolean', null: 'null' })[schema.type] ?? 'unknown';
}
function parameters(items) {
  return `{ ${items.map((p) => `${JSON.stringify(p.name)}${p.required ? '' : '?'}: ${type(p.schema)};`).join(' ')} }`;
}
let output = `// Generated by scripts/generate-api.mjs; do not edit.\n// Source: https://spectrum.photon.codes/openapi/json\n// Snapshot SHA-256: ${hash}\n\nexport interface SpectrumOperations {\n`;
const routes = {};
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const key = `${method.toUpperCase()} ${path}`;
    const pathParams = (op.parameters ?? []).filter((p) => p.in === 'path' && p.name !== 'projectId');
    const query = (op.parameters ?? []).filter((p) => p.in === 'query');
    const body = op.requestBody?.content?.['application/json']?.schema;
    const response = op.responses['200']?.content?.['application/json']?.schema?.properties?.data;
    output += `  ${JSON.stringify(key)}: {\n`;
    if (pathParams.length) output += `    path: ${parameters(pathParams)};\n`;
    if (query.length) output += `    query${query.some((p) => p.required) ? '' : '?'}: ${parameters(query)};\n`;
    if (body) output += `    body${op.requestBody.required ? '' : '?'}: ${type(body)};\n`;
    output += `    response: ${response ? type(response) : 'Response'};\n  };\n`;
    routes[key] = path.includes('{projectId}');
  }
}
output += '}\n';
mkdirSync(new URL('packages/api/src/', root), { recursive: true });
function emit(path, content) {
  const url = new URL(path, root);
  if (check) {
    if (readFileSync(url, 'utf8') !== content) throw new Error(`${path} is stale; run node scripts/generate-api.mjs`);
  } else writeFileSync(url, content);
}
emit('packages/api/src/api-types.ts', output);
emit('packages/api/src/api-routes.ts', `// Generated by scripts/generate-api.mjs; do not edit.\nexport const spectrumRoutes = ${JSON.stringify(routes, null, 2)} as const;\n`);
console.log(`Generated ${Object.keys(routes).length} operations; snapshot SHA-256 ${hash}`);
