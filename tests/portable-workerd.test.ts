import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'vitest';
import { build } from 'esbuild';
import { Miniflare } from 'miniflare';

const profile = { projectId: 'portable-project', firstName: 'Worker', lastName: 'Integration', avatarUrl: null };
const failure = { succeed: false, data: null, code: 'NO_AVAILABLE_IMESSAGE_LINE', message: 'No test line available' };
const calls: { url: string; method: string; authorization: string | null; accept: string | null; contentType: string | null; body: string }[] = [];
let worker: Miniflare;

describe('portable management and webhooks in workerd (no nodejs_compat)', () => {
  beforeAll(async () => {
    const bundle = await build({
      entryPoints: ['tests/fixtures/portable-worker.ts'],
      bundle: true,
      platform: 'browser',
      format: 'esm',
      target: 'es2022',
      write: false,
      metafile: true,
    });
    // No external imports, Node builtin aliases, injected shims, or runtime adapter.
    expect(bundle.metafile!.outputs[Object.keys(bundle.metafile!.outputs)[0]!]!.imports).toEqual([]);
    worker = new Miniflare({
      modules: true,
      script: bundle.outputFiles[0]!.text,
      compatibilityDate: '2026-07-30',
      compatibilityFlags: [],
      outboundService: async (request: Request) => {
        calls.push({
          url: request.url,
          method: request.method,
          authorization: request.headers.get('authorization'),
          accept: request.headers.get('accept'),
          contentType: request.headers.get('content-type'),
          body: await request.text(),
        });
        if (request.url === 'https://management.invalid/projects/portable-project/profile') {
          return Response.json({ succeed: true, data: profile });
        }
        if (request.url === 'https://management.invalid/projects/portable-project/lines/route') {
          return Response.json(failure, { status: 503, headers: { 'x-request-id': 'workerd-request' } });
        }
        return new Response('Unexpected outbound request', { status: 500 });
      },
    });
    await worker.ready;
  });

  beforeEach(() => { calls.length = 0; });
  afterAll(async () => { await worker?.dispose(); });

  it('uses native fetch with UTF-8 Basic auth and decodes a management success envelope', async () => {
    const response = await worker.dispatchFetch('https://worker.test/management/profile');
    expect(response.status, `${JSON.stringify(calls)} ${await response.clone().text()}`).toBe(200);
    expect(await response.json()).toEqual(profile);
    expect(calls).toEqual([{
      url: 'https://management.invalid/projects/portable-project/profile',
      method: 'PATCH',
      authorization: `Basic ${Buffer.from('portable-project:sëcret🔑', 'utf8').toString('base64')}`,
      accept: 'application/json',
      contentType: 'application/json',
      body: '{"firstName":"Worker","lastName":"Integration"}',
    }]);
  });

  it('preserves the upstream HTTP error, structured body, and headers without retries', async () => {
    const response = await worker.dispatchFetch('https://worker.test/management/error');
    expect(response.status, `${JSON.stringify(calls)} ${await response.clone().text()}`).toBe(503);
    expect(await response.json()).toEqual({
      name: 'SpectrumApiError', kind: 'http', status: 503,
      code: failure.code, message: failure.message, body: failure,
      rawBody: JSON.stringify(failure), requestId: 'workerd-request',
    });
    expect(calls).toHaveLength(1);
    expect(calls[0]).toMatchObject({
      url: 'https://management.invalid/projects/portable-project/lines/route',
      method: 'GET', body: '', contentType: null,
      authorization: `Basic ${Buffer.from('portable-project:sëcret🔑', 'utf8').toString('base64')}`,
    });
  });

  // Independent Python stdlib hmac/hashlib fixtures, not signatures generated by the SDK.
  // Standard key = bytes(range(32)); legacy key = literal UTF-8 secret in the Worker.
  it.each([
    {
      scheme: 'legacy', signatureHeader: 'x-spectrum-signature',
      headers: { 'x-spectrum-timestamp': '1800000000' },
      signature: 'v0=6f6ccc463ca4368ce3493d08bacbeb9dcfae04def710a76bd9ddbbb69f3e052c',
      badSignature: `v0=${'0'.repeat(64)}`,
    },
    {
      scheme: 'standard', signatureHeader: 'webhook-signature',
      headers: { 'webhook-id': 'evt_independent', 'webhook-timestamp': '1800000000' },
      signature: 'v1,EZnIN1oEhr3xGHWGOkBwNJeMUQlO9rIRLMOWxQZOM50=',
      badSignature: `v1,${'A'.repeat(43)}=`,
    },
  ])('verifies $scheme fixtures with real Web Crypto and rejects invalid signatures', async (fixture) => {
    const send = (signature: string) => worker.dispatchFetch(`https://worker.test/${fixture.scheme}`, {
      method: 'POST',
      headers: { ...fixture.headers, [fixture.signatureHeader]: signature },
      body: '{"text":"héllo 🌈","ok":true}',
    });
    const accepted = await send(fixture.signature);
    expect(accepted.status).toBe(200);
    expect(await accepted.json()).toEqual({ text: 'héllo 🌈', ok: true });
    const rejected = await send(fixture.badSignature);
    expect(rejected.status).toBe(401);
    expect(await rejected.json()).toEqual({ name: 'WebhookVerificationError', code: 'signature' });
    expect(calls).toEqual([]);
  });
});
